import { Hono } from 'hono';
import { cors } from 'hono/cors';
import { swaggerUI } from '@hono/swagger-ui';
import { OpenAPIHono } from '@hono/zod-openapi';
import { logger } from './middlewares/logger';
import { config } from './config/config';
import { requireAuth } from './middlewares/auth.middleware';
import { requireOwnProject } from './middlewares/require-own-project.middleware';
import { rateLimiter } from './middlewares/rate-limit.middleware';
import { registerSalesOrdersRoutes } from './routes/sales-orders.routes';
import { validationHook } from './lib/validation-hook';
import { errorHandler } from './lib/error-handler';

const app = new Hono();
const apiV1 = new OpenAPIHono({
  defaultHook: validationHook,
});

// CORS middleware
app.use('*', cors({
  origin: config.cors.origin,
  allowHeaders: ['Content-Type', 'Authorization', 'x-own-project-id'],
  allowMethods: ['GET', 'POST', 'PATCH', 'PUT', 'DELETE', 'OPTIONS'],
  maxAge: 600,
  // Auth is a Bearer token, not cookies, so no request needs credentials
  // mode - and the fetch spec forbids Access-Control-Allow-Origin: * paired
  // with Access-Control-Allow-Credentials: true for a credentialed request.
  credentials: config.cors.origin !== '*',
}));

// Logger middleware
app.use('*', logger());

// Bearer JWT auth - lets Swagger UI's "Authorize" button attach
// `Authorization: Bearer <token>` to every request that requires it
// (see `security` on each route).
apiV1.openAPIRegistry.registerComponent('securitySchemes', 'Bearer', {
  type: 'http',
  scheme: 'bearer',
  bearerFormat: 'JWT',
});

// x-own-project-id tenant header (see require-own-project.middleware.ts) -
// registered the same way as Bearer so Swagger UI's "Authorize" dialog
// lets you set it once and have it attached to every sales-order request,
// instead of typing it into each operation's "Try it out" form.
apiV1.openAPIRegistry.registerComponent('securitySchemes', 'OwnProjectId', {
  type: 'apiKey',
  in: 'header',
  name: 'x-own-project-id',
});

// The OpenAPI documentation will be auto-generated by @hono/zod-openapi
apiV1.doc('/openapi.json', {
  openapi: '3.0.0',
  info: {
    title: 'Comercyo Pedidos de venta API',
    version: '1.0.0',
    description: 'Backend del módulo Pedidos de venta de Comercyo.',
  },
  servers: [
    {
      url: `${config.productionUrl}/api/v1`,
      description: 'Production server',
    },
    {
      url: `http://localhost:${config.port}/api/v1`,
      description: 'Development server',
    },
  ],
});

apiV1.get('/doc', swaggerUI({ url: '/api/v1/openapi.json' }));

// Best-effort abuse mitigation ahead of auth - see rate-limit.middleware.ts
// for why this is per-warm-instance rather than a global guarantee.
//
// A single '/sales-orders/*' registration is enough - Hono's wildcard
// pattern also matches the bare '/sales-orders' path. A parallel
// '/sales-orders' registration alongside it is NOT a no-op - it makes every
// middleware below run twice per request to the bare path, so don't add one.
//
// requireOwnProject() reads the x-own-project-id header independently of
// auth, so its order relative to requireAuth() doesn't matter - but it
// runs after the rate limiter so an unauthenticated/unscoped flood is
// still throttled before hitting the DB.
apiV1.use('/sales-orders/*', rateLimiter({ windowMs: 60_000, max: 100 }));
apiV1.use('/sales-orders/*', requireAuth());
apiV1.use('/sales-orders/*', requireOwnProject());

registerSalesOrdersRoutes(apiV1);

app.route('/api/v1', apiV1);

// 404 handler
app.notFound((c) => {
  return c.json({ 
    success: false,
    error: 'Not Found', 
    path: c.req.path 
  }, 404);
});

// Error handler
app.onError(errorHandler);

export default app;
